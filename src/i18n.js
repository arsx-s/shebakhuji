const STORAGE_KEY = 'shebashathi.lang';
const SUPPORTED = ['bn', 'en'];

/** Exposed for the localisation test suite. */
export const dictionaries = DICT;
export const supportedLanguages = SUPPORTED;

function detectInitial() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && SUPPORTED.includes(stored)) return stored;
  } catch { /* storage blocked */ }
  const nav = typeof navigator === 'undefined' ? {} : navigator;
  const candidates = [nav.language, ...(nav.languages || [])];
  return candidates.some((l) => /^bn/i.test(l || '')) ? 'bn' : 'en';
}

let lang = detectInitial();
const listeners = new Set();

/** Reflect the active language onto the document (no-op outside a browser). */
function applyToDocument(value) {
  if (typeof document === 'undefined' || !document.documentElement) return;
  document.documentElement.lang = value;
  document.documentElement.dataset.lang = value;
}

function prettify(key) {
  const tail = String(key).split('.').pop() || String(key);
  return tail.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (c) => c.toUpperCase());
}

/** Translate a key, interpolating {placeholders}. */
export function t(key, vars) {
  if (key == null) return '';
  const table = DICT[lang] || DICT.en;
  let value = table[key] ?? DICT.en[key] ?? prettify(key);
  if (vars) {
    value = String(value).replace(/\{(\w+)\}/g, (match, name) => (vars[name] != null ? String(vars[name]) : match));
  }
  return value;
}

export function getLang() { return lang; }

export function setLang(next) {
  const value = SUPPORTED.includes(next) ? next : 'bn';
  if (value === lang) { applyToDocument(value); return; }
  lang = value;
  try { localStorage.setItem(STORAGE_KEY, value); } catch { /* ignore */ }
  applyToDocument(value);
  listeners.forEach((fn) => { try { fn(value); } catch { /* keep others */ } });
}

/** Called once at boot so the document matches the stored language. */
export function initLang() { applyToDocument(lang); return lang; }

export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }
export function toggleLang() { setLang(lang === 'bn' ? 'en' : 'bn'); }

const locale = () => (lang === 'bn' ? 'bn-BD' : 'en-BD');

export function formatNumber(value, options) {
  const n = Number(value || 0);
  return new Intl.NumberFormat(locale(), options).format(n);
}

/** Format integer paisa as Bangla/English taka. */
export function money(paisa) {
  const value = Number(paisa || 0) / 100;
  const formatted = new Intl.NumberFormat(locale(), { minimumFractionDigits: 0, maximumFractionDigits: value % 1 === 0 ? 0 : 2 }).format(value);
  return `৳${formatted}`;
}

export function formatDate(value, options) {
  if (!value) return '—';
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  return new Intl.DateTimeFormat(locale(), options || { day: 'numeric', month: 'short', year: 'numeric' }).format(date);
}

export function formatDateTime(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  return new Intl.DateTimeFormat(locale(), { day: 'numeric', month: 'short', hour: 'numeric', minute: '2-digit' }).format(date);
}

export function formatTime(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  return new Intl.DateTimeFormat(locale(), { hour: 'numeric', minute: '2-digit' }).format(date);
}

export function relativeDay(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  const today = new Date(); today.setHours(0, 0, 0, 0);
  const target = new Date(date); target.setHours(0, 0, 0, 0);
  const diff = Math.round((target - today) / 86400000);
  if (diff === 0) return t('common.today');
  if (diff === 1) return t('common.tomorrow');
  if (diff === -1) return t('common.yesterday');
  return formatDate(date);
}
